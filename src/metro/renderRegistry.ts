import fs from 'node:fs';
import path from 'node:path';
import type { IconData, MaterialSymbolVariant } from '../types';

/** 'd' = FILL 0 (filled={false} or absent), 'f' = FILL 1 (filled). */
export type Shape = 'd' | 'f';

/** variant → icon name (aliases already resolved to their target) → shapes the app renders */
export type IconUses = Map<MaterialSymbolVariant, Map<string, Set<Shape>>>;

export interface RenderRegistryInput {
  uses: IconUses;
  /** used names that are aliases, name → target; written so the runtime resolves the alias the app wrote */
  aliases: Record<string, string>;
  /** icon data of one variant; a name absent from it is skipped */
  loadVariant: (variant: MaterialSymbolVariant) => Record<string, IconData>;
}

export interface RenderRegistryOutput {
  code: string;
  /** icons per variant, each counted once whatever its shapes */
  count: Partial<Record<MaterialSymbolVariant, number>>;
  /** path data shipped, in characters (each distinct path counted once) */
  bytes: number;
  /** shapes shipped: `d`, `f`, and `f` that is the same path as `d` (no extra data) */
  shapes: { d: number; f: number; shared: number };
  aliasesUsed: number;
}

/**
 * The registry inlines only the paths the app renders, one shape per use. A filled icon whose FILL 1 path equals its
 * FILL 0 path (no `f` in the data) points both shapes at one string. Each distinct path is declared once as a
 * variable, so an icon used in several variants or shapes never repeats its data.
 */
export function renderRegistry({ uses, aliases, loadVariant }: RenderRegistryInput): RenderRegistryOutput {
  const pathVars = new Map<string, string>();
  const decls: string[] = [];
  const ref = (d: string): string => {
    let name = pathVars.get(d);
    if (!name) {
      name = `p${pathVars.size}`;
      pathVars.set(d, name);
      decls.push(`${name}=${JSON.stringify(d)}`);
    }
    return name;
  };

  const count: Partial<Record<MaterialSymbolVariant, number>> = {};
  const shapes = { d: 0, f: 0, shared: 0 };
  const variantBlocks: string[] = [];
  for (const variant of [...uses.keys()].sort()) {
    const byName = uses.get(variant) as Map<string, Set<Shape>>;
    const data = loadVariant(variant);
    const entries: string[] = [];
    for (const name of [...byName.keys()].sort()) {
      const icon = data[name];
      if (!icon) continue;
      const wanted = byName.get(name) as Set<Shape>;
      const fields: string[] = [];
      if (wanted.has('d')) {
        fields.push(`d:${ref(icon.d)}`);
        shapes.d += 1;
      }
      if (wanted.has('f')) {
        fields.push(`f:${ref(icon.f ?? icon.d)}`);
        if (icon.f === undefined) shapes.shared += 1;
        else shapes.f += 1;
      }
      entries.push(`${JSON.stringify(name)}:{${fields.join(',')}}`);
    }
    count[variant] = entries.length;
    variantBlocks.push(`${variant}:{${entries.join(',')}}`);
  }

  const usedAliases = Object.fromEntries(Object.keys(aliases).sort().map((k) => [k, aliases[k]]));
  const lines = ['// @generated by rn-material-symbols — do not edit'];
  if (decls.length > 0) lines.push(`var ${decls.join(',\n')};`);
  lines.push(`module.exports={mode:'scanned',icons:{${variantBlocks.join(',')}},aliases:${JSON.stringify(usedAliases)}};`, '');
  let bytes = 0;
  for (const d of pathVars.keys()) bytes += d.length;
  return { code: lines.join('\n'), count, bytes, shapes, aliasesUsed: Object.keys(usedAliases).length };
}

/** Reads icons/<variant>.json from the package once per process. */
export function variantLoader(iconsDir: string): (variant: MaterialSymbolVariant) => Record<string, IconData> {
  const cache = new Map<MaterialSymbolVariant, Record<string, IconData>>();
  return (variant) => {
    let data = cache.get(variant);
    if (!data) {
      data = JSON.parse(fs.readFileSync(path.join(iconsDir, `${variant}.json`), 'utf8')) as Record<string, IconData>;
      cache.set(variant, data);
    }
    return data;
  };
}

export function writeIfChanged(file: string, code: string): boolean {
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8') === code) return false;
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.${process.pid}.tmp`;
  fs.writeFileSync(tmp, code);
  fs.renameSync(tmp, file);
  return true;
}
