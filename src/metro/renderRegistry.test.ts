import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { renderRegistry, writeIfChanged } from './renderRegistry';

// every temp dir this file creates is removed after the file's tests
const createdTempDirs: string[] = [];
function tempDir(prefix: string): string {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), prefix));
  createdTempDirs.push(dir);
  return dir;
}
afterAll(() => {
  for (const dir of createdTempDirs) fs.rmSync(dir, { recursive: true, force: true });
});

const data: Record<string, Record<string, { d: string; f?: string }>> = {
  rounded: { info: { d: 'I0', f: 'I1' }, schedule: { d: 'S0' }, home: { d: 'H0', f: 'H1' } },
  outlined: { info: { d: 'OI0', f: 'OI1' } },
};
const loadVariant = (v: string) => data[v] ?? {};
const uses = (entries: Array<[string, string, string[]]>) => {
  const m = new Map<never, Map<string, Set<'d' | 'f'>>>();
  for (const [variant, name, shapes] of entries) {
    const byName = m.get(variant as never) ?? new Map<string, Set<'d' | 'f'>>();
    byName.set(name, new Set(shapes as Array<'d' | 'f'>));
    m.set(variant as never, byName);
  }
  return m;
};

test('inlines only the shapes in use, each distinct path once', () => {
  const out = renderRegistry({
    uses: uses([['rounded', 'info', ['f']], ['rounded', 'home', ['d', 'f']], ['rounded', 'schedule', ['d', 'f']]]),
    aliases: { access_time: 'schedule' },
    loadVariant,
  });
  expect(out.code).toBe(
    [
      '// @generated by rn-material-symbols — do not edit',
      'var p0="H0",',
      'p1="H1",',
      'p2="I1",',
      'p3="S0";',
      'module.exports={mode:\'scanned\',icons:{rounded:{"home":{d:p0,f:p1},"info":{f:p2},"schedule":{d:p3,f:p3}}},aliases:{"access_time":"schedule"}};',
      '',
    ].join('\n'),
  );
  expect(out.count).toEqual({ rounded: 3 });
  expect(out.shapes).toEqual({ d: 2, f: 2, shared: 1 });
  expect(out.bytes).toBe(8);
  expect(out.aliasesUsed).toBe(1);
});

test('the generated module evaluates to the registry contract', () => {
  const out = renderRegistry({ uses: uses([['rounded', 'info', ['d']], ['outlined', 'info', ['f']]]), aliases: {}, loadVariant });
  const mod = { exports: {} as Record<string, unknown> };
  new Function('module', out.code)(mod);
  expect(mod.exports).toEqual({ mode: 'scanned', icons: { outlined: { info: { f: 'OI1' } }, rounded: { info: { d: 'I0' } } }, aliases: {} });
});

test('skips names a variant does not have, and writes an empty registry for no uses', () => {
  const out = renderRegistry({ uses: uses([['outlined', 'schedule', ['d']]]), aliases: {}, loadVariant });
  expect(out.count).toEqual({ outlined: 0 });
  const empty = renderRegistry({ uses: new Map(), aliases: {}, loadVariant });
  expect(empty.code).toContain("module.exports={mode:'scanned',icons:{},aliases:{}};");
});

test('output is deterministic regardless of input order', () => {
  const a = renderRegistry({ uses: uses([['rounded', 'schedule', ['d']], ['rounded', 'info', ['f', 'd']]]), aliases: {}, loadVariant }).code;
  const b = renderRegistry({ uses: uses([['rounded', 'info', ['d', 'f']], ['rounded', 'schedule', ['d']]]), aliases: {}, loadVariant }).code;
  expect(a).toBe(b);
});

test('writeIfChanged only touches the file when content differs', () => {
  const file = path.join(tempDir('rnms-'), 'deep', 'registry.js');
  expect(writeIfChanged(file, 'a')).toBe(true);
  expect(writeIfChanged(file, 'a')).toBe(false);
  expect(writeIfChanged(file, 'b')).toBe(true);
  expect(fs.readFileSync(file, 'utf8')).toBe('b');
});
